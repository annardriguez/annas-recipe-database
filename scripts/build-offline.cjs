// Regenerate after changing any public app file. No account data enters this manifest.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const files=fs.readdirSync(root).filter(n=>/\.(html|css|js)$/.test(n)&&!['sw.js','supabase-config.js'].includes(n));
function assets(dir){for(const item of fs.readdirSync(path.join(root,dir),{withFileTypes:true})){const name=dir+'/'+item.name;if(item.isDirectory())assets(name);else if(/\.(jpg|jpeg|png|svg|webp|ttf|woff2|css)$/.test(name))files.push(name);}}
assets('assets');files.push('vendor/appwrite-29.2.0.js','manifest.webmanifest');files.sort();
const hash=crypto.createHash('sha256');for(const name of files){hash.update(name);hash.update(fs.readFileSync(path.join(root,name)));}
const version=hash.digest('hex').slice(0,16);
fs.writeFileSync(path.join(root,'sw.js'),`/* Generated by npm run build:offline. Public app files only. */
const FILES=${JSON.stringify(files,null,2)};
const PREFIX='anna-kitchen-shell:'+new URL(self.registration.scope).pathname+':';
const CACHE=PREFIX+'${version}';
const allowed=new Set(FILES.map(file=>new URL(file,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil((async()=>{
  try {const cache=await caches.open(CACHE);await cache.addAll(FILES.map(file=>new Request(new URL(file,self.registration.scope),{cache:'reload'})));}
  catch(error){await caches.delete(CACHE);throw error;}
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  for(const name of await caches.keys())if(name.startsWith(PREFIX)&&name!==CACHE)await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const url=new URL(event.request.url);url.search='';url.hash='';
  if(url.href===self.registration.scope)url.pathname+='index.html';
  if(!allowed.has(url.href))return; // Never cache accounts, API calls, or private photos.
  event.respondWith(caches.open(CACHE).then(async cache=>(await cache.match(url.href))||fetch(event.request)));
});
`);
console.log(`Offline shell ${version}: ${files.length} public files`);
