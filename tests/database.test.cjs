const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {PGlite} = require('@electric-sql/pglite');
const userA = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const userB = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
test('migration: owner RLS, private storage, atomic changes, conflicts, tombstones and safe import', async () => {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth; create schema storage;
    create table auth.users (id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid $$;
    grant usage on schema public, auth, storage to authenticated, anon;
    grant execute on function auth.uid() to authenticated, anon;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid primary key,bucket_id text,name text);
    alter table storage.objects enable row level security;
    grant select,insert,delete on storage.objects to authenticated;
    create function storage.foldername(text) returns text[] language sql as $$ select string_to_array($1,'/') $$;
    insert into auth.users values ('${userA}'),('${userB}');
    create table public.recipe_favourites(user_id uuid,recipe_id text);
    insert into public.recipe_favourites values ('${userA}','legacy-recipe');
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261112224216_personal_kitchen.sql','utf8'));
  const sql = (q,args=[]) => db.query(q,args);
  const asUser = async id => {await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${id}',false);`);};
  const save = changes => sql('select * from public.save_kitchen_records($1::jsonb)',[JSON.stringify(changes)]);
  const change = (id,data,version=0,deleted=false) => ({kind:'entry',id,data,expected_version:version,deleted});
  await asUser(userA);
  assert.equal((await sql('select id from kitchen_records')).rows[0].id,'legacy-recipe');
  let result = await save([change('dinner',{notes:'Less salt'})]);
  assert.equal(result.rows[0].version,1);
  await asUser(userB);
  assert.equal((await sql('select * from kitchen_records')).rows.length,0);
  await assert.rejects(sql('insert into kitchen_records(user_id,kind,id) values ($1,\'entry\',\'stolen\')',[userA]),/row-level security/);
  await save([change('dinner',{notes:'Different kitchen'})]);
  await asUser(userA);
  assert.equal((await sql("select data from kitchen_records where kind='entry'")).rows[0].data.notes,'Less salt');
  await save([change('dinner',{notes:'More herbs'},1)]);
  await assert.rejects(save([change('should-rollback',{notes:'No partial saves'}),change('dinner',{notes:'Stale'},1)]),/changed on another device/);
  assert.equal((await sql("select * from kitchen_records where id='should-rollback'")).rows.length,0);
  await save([change('dinner',{},2,true)]);
  await assert.rejects(save([change('dinner',{notes:'Stale resurrection'},2)]),/changed on another device/);
  const imported = [{kind:'entry',id:'dinner',data:{notes:'Old guest data'}},{kind:'recipe',id:'guest-original',data:{title:'Guest pasta'}}];
  await sql('select import_kitchen_guest($1)',[JSON.stringify(imported)]);
  await sql('select import_kitchen_guest($1)',[JSON.stringify(imported)]);
  assert.equal((await sql("select deleted from kitchen_records where id='dinner'")).rows[0].deleted,true);
  assert.equal((await sql("select * from kitchen_records where id='guest-original'")).rows.length,1);
  await sql('insert into storage.objects values ($1, $2, $3)',[userA,'kitchen-photos',`${userA}/dish.jpg`]);
  await assert.rejects(sql('insert into storage.objects values ($1,$2,$3)',[userB,'kitchen-photos',`${userB}/dish.jpg`]),/row-level security/);
  await asUser(userB);
  assert.equal((await sql('select * from storage.objects')).rows.length,0);
  await db.exec('reset role; set role anon;');
  await assert.rejects(sql('select * from kitchen_records'),/permission denied/);
  await assert.rejects(save([change('guest',{notes:'No access'})]),/permission denied/);
  await db.exec('reset role;');
  assert.equal((await sql("select public from storage.buckets where id='kitchen-photos'")).rows[0].public,false);
  await db.close();
});
